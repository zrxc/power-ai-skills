  function buildStatusPayload() {
    const quickstart = buildQuickstartPayload();
    const defaults = buildDefaultsPayload();
    const doctor = doctorService.collectDoctorReport();
    const habitCapture = buildHabitCapturePayload({
      workspaceInitialized: quickstart.workspace.workspaceInitialized,
      projectLocalDraftCount: quickstart.workspace.projectLocalDraftCount
    });
    const latestSyncFollowUpNeedsAttention = habitCapture.latestSyncFollowUp.available
      && habitCapture.latestSyncFollowUp.recommendation?.requiresAttention;
    const needsAttention = !doctor.ok || quickstart.status !== "ready" || latestSyncFollowUpNeedsAttention;
    const title = doctor.mode === "package-maintenance"
      ? "Current project is in package-maintenance mode; use this view mainly for consumer projects."
      : needsAttention
        ? "Current consumer project still has onboarding or workspace follow-up work."
        : "Current consumer project is ready for the normal day-to-day flow.";

    return {
      packageName: context.packageJson.name,
      version: context.packageJson.version,
      projectRoot,
      mode: doctor.mode,
      status: doctor.mode === "package-maintenance"
        ? "package-maintenance"
        : needsAttention ? "attention" : "ready",
      title,
      selection: {
        summary: quickstart.selectionSummary,
        defaultSummary: selectionService.getSelectionSummary(defaults.effectiveSelection),
        requestedProjectProfile: defaults.requestedProjectProfile || "",
        recommendedProjectProfile: defaults.recommendedProjectProfile || "",
        recommendedProjectProfileReason: defaults.recommendedProjectProfileReason || "",
        source: defaults.effectiveSelection.sourceDescription || "manual"
      },
      workspace: {
        doctorOk: doctor.ok,
        failureCodes: doctor.failureCodes || [],
        warningCount: (doctor.warnings || []).length,
        checkGroupCount: (doctor.checkGroups || []).length,
        reportPath: doctor.reportPath,
        jsonPath: doctor.jsonPath,
        nextSteps: doctor.nextSteps || []
      },
      habitCapture,
      quickstart: {
        status: quickstart.status,
        title: quickstart.title,
        recommendedPath: quickstart.recommendedPath
      },
      references: quickstart.references
    };
  }

